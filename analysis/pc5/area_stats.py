#!/usr/bin/env python3
"""Time series of subsidence-affected area (<-2 cm and <-5 cm) per acquisition date.

Reads per-date cumulative displacement stacks generated by ``analysis/cumulative.py``:
  - analysis/out/central_valley_cum_stack.npz
  - analysis/out/karapinar_cum_stack.npz

Writes:
  - data/central_valley/area_stats.json
  - data/karapinar/area_stats.json
  - docs/story/media/pc5_area_cv.png

Usage:
    python analysis/pc5/area_stats.py
"""
from __future__ import annotations

import argparse
import json
import sys
import warnings
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from analysis.pc5.uncertainty_map import DISCLAIMER, SITE_BBOX, utm_to_lonlat  # noqa: E402

BLOCK_PX = 13
BLOCK_MIN_VALID = 0.5
BLOCK_MAX_STD = 2.0

DEFAULT_PNG = ROOT / "docs" / "story" / "media" / "pc5_area_cv.png"


def block_median_1km(
    arr: np.ndarray,
    block: int = BLOCK_PX,
    min_valid: float = BLOCK_MIN_VALID,
    max_std: float | None = BLOCK_MAX_STD,
) -> np.ndarray:
    """Compute ~1 km (13x13 px) NaN-median block summary matching analysis/cumulative.py."""
    h, w = arr.shape
    hp = -(-h // block) * block
    wp = -(-w // block) * block
    pad = np.full((hp, wp), np.nan, dtype=np.float32)
    pad[:h, :w] = arr
    tiles = pad.reshape(hp // block, block, wp // block, block)
    frac = np.isfinite(tiles).mean(axis=(1, 3))
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        med = np.nanmedian(tiles, axis=(1, 3))
    med[frac < min_valid] = np.nan
    if max_std is not None:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", RuntimeWarning)
            sd = np.nanstd(tiles, axis=(1, 3))
        med[~(sd <= max_std)] = np.nan
    full = np.repeat(np.repeat(med, block, 0), block, 1)[:h, :w]
    centre = np.zeros((h, w), dtype=bool)
    centre[block // 2 :: block, block // 2 :: block] = True
    return np.where(centre & np.isfinite(arr), full, np.nan).astype(np.float32)


def compute_site_area_stats(
    site: str,
    stack_path: Path | None = None,
    bbox: tuple[float, float, float, float] | None = None,
) -> dict:
    """Compute per-date affected area (<-2 cm, <-5 cm), peak block-median, and spatial median."""
    npz_file = stack_path or (ROOT / "analysis" / "out" / f"{site}_cum_stack.npz")
    if not npz_file.exists():
        raise FileNotFoundError(f"Cumulative stack not found: {npz_file}")

    site_bbox = tuple(bbox) if bbox is not None else tuple(SITE_BBOX[site])
    d = np.load(npz_file, allow_pickle=False)
    stack = np.asarray(d["cum_stack_cm"], dtype=np.float32)
    dates = [str(dt) for dt in d["dates"]]
    x = np.asarray(d["x"], dtype=np.float64)
    y = np.asarray(d["y"], dtype=np.float64)
    epsg = int(d["epsg"])
    quality = str(d["quality"]) if "quality" in d else "provisional"

    xx, yy = np.meshgrid(x, y)
    lon, lat = utm_to_lonlat(xx, yy, epsg)
    w, s, e, n = site_bbox
    in_bbox = (lon >= w) & (lon <= e) & (lat >= s) & (lat <= n)

    # Consistent valid mask matching cumulative.py (finite in final epoch & inside bbox)
    valid_mask = np.isfinite(stack[-1]) & in_bbox
    pixel_area_km2 = abs(float(x[1] - x[0]) * float(y[1] - y[0])) / 1e6
    n_valid = int(valid_mask.sum())

    area_lt_2: list[float] = []
    area_lt_5: list[float] = []
    max_sub: list[float] = []
    med_cm: list[float] = []

    for k in range(stack.shape[0]):
        arr = np.where(valid_mask, stack[k], np.nan)
        vals = arr[valid_mask]
        a2 = float(np.sum(vals < -2.0)) * pixel_area_km2
        a5 = float(np.sum(vals < -5.0)) * pixel_area_km2
        area_lt_2.append(round(a2, 2))
        area_lt_5.append(round(a5, 2))
        med_cm.append(round(float(np.median(vals)), 3))

        bm = block_median_1km(arr)
        bm_valid = bm[np.isfinite(bm)]
        peak = float(np.min(bm_valid)) if bm_valid.size > 0 else float(np.min(vals))
        max_sub.append(round(peak, 2))

    return {
        "site": site,
        "dates": dates,
        "area_km2_lt_2cm": area_lt_2,
        "area_km2_lt_5cm": area_lt_5,
        "max_subsidence_cm": max_sub,
        "median_cm": med_cm,
        "pixel_area_km2": round(pixel_area_km2, 6),
        "valid_pixels": n_valid,
        "valid_area_km2": round(n_valid * pixel_area_km2, 2),
        "bbox": list(site_bbox),
        "unit_area": "km^2",
        "unit_disp": "cm (LOS, negative = subsidence)",
        "quality": quality,
        "quality_note": DISCLAIMER,
        "method": (
            f"Per-epoch pixel count within site bbox exceeding -2.0 cm and -5.0 cm LOS thresholds "
            f"multiplied by pixel area ({pixel_area_km2:.4f} km^2 for 80 m grid) over common valid pixels; "
            f"max_subsidence_cm uses 13x13 pixel (~1 km) block-median matching analysis/cumulative.py."
        ),
    }


def make_area_figure(cv_stats: dict, kp_stats: dict, out_png: Path = DEFAULT_PNG) -> None:
    """Create a 2-panel time-series figure for Central Valley and Karapinar affected area."""
    fig, axes = plt.subplots(1, 2, figsize=(13.2, 5.2), dpi=180)
    fig.patch.set_facecolor("white")

    panels = [
        (axes[0], cv_stats, "A. Central Valley Affected Area (28 Jun–14 Oct 2026)"),
        (axes[1], kp_stats, "B. Karapınar Affected Area (26 Jun–12 Oct 2026)"),
    ]

    for ax, st, title in panels:
        dates = [d[5:] for d in st["dates"]]  # MM-DD for compact readable ticks
        x_idx = np.arange(len(dates))
        a2 = st["area_km2_lt_2cm"]
        a5 = st["area_km2_lt_5cm"]
        peak = [abs(v) for v in st["max_subsidence_cm"]]

        b1 = ax.bar(x_idx - 0.16, a2, width=0.32, color="#2563eb", alpha=0.82, label=f"Area < -2 cm LOS (final: {a2[-1]:,.1f} km²)")
        b2 = ax.bar(x_idx + 0.16, a5, width=0.32, color="#dc2626", alpha=0.88, label=f"Area < -5 cm LOS (final: {a5[-1]:,.1f} km²)")

        ax.set_title(title, fontsize=11.0, fontweight="bold", pad=10)
        ax.set_xticks(x_idx)
        ax.set_xticklabels(dates, rotation=32, ha="right", fontsize=8.8)
        ax.set_ylabel("Subsiding Area (km²)", fontsize=10.0)
        ax.set_ylim(0, max(max(a2), 1.0) * 1.24)
        ax.grid(True, axis="y", linestyle="--", alpha=0.35)

        ax2 = ax.twinx()
        ln = ax2.plot(x_idx, peak, color="#0f172a", marker="o", linewidth=1.9, markersize=5, label=f"Peak 1 km |LOS| (final: {peak[-1]:.1f} cm)")
        ax2.set_ylabel("Peak 1 km Subsidence |LOS| (cm)", fontsize=9.8, color="#0f172a")
        ax2.set_ylim(0, max(max(peak), 1.0) * 1.22)

        handles = [b1, b2, ln[0]]
        labels = [h.get_label() for h in handles]
        ax.legend(handles, labels, loc="upper left", fontsize=8.2, frameon=True, framealpha=0.92)

    fig.suptitle("NISAR Provisional Cumulative Subsidence Extent Over 108 Days", fontsize=12.5, fontweight="bold", y=0.98)
    fig.text(
        0.5,
        0.01,
        "Data: NASA-ISRO NISAR L2 GUNW (provisional), ASF DAAC. Analysis: Team Taykut.",
        ha="center",
        fontsize=8.5,
        color="#475569",
    )
    fig.tight_layout(rect=[0.0, 0.04, 1.0, 0.94])
    out_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_png, dpi=180, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description="Compute per-date affected area time series.")
    parser.add_argument("--png", type=Path, default=DEFAULT_PNG)
    args = parser.parse_args()

    results = {}
    for site in ("central_valley", "karapinar"):
        stats = compute_site_area_stats(site)
        out_json = ROOT / "data" / site / "area_stats.json"
        out_json.write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")
        results[site] = stats
        print(
            f"[{site}] valid_area={stats['valid_area_km2']:.1f} km2 | "
            f"final <-2cm={stats['area_km2_lt_2cm'][-1]:.1f} km2 | "
            f"final <-5cm={stats['area_km2_lt_5cm'][-1]:.1f} km2 | "
            f"final peak={stats['max_subsidence_cm'][-1]:.2f} cm"
        )

    make_area_figure(results["central_valley"], results["karapinar"], args.png)
    print(f"Wrote {args.png}")


if __name__ == "__main__":
    main()
